# ---------------------------------------------------------------- helpers ---
def P(text, style=body):
    return Paragraph(text, style)


def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def add_heading(story, text, style=h1s, level=0, rule=True):
    key = 'h_' + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    blocks = [p]
    if rule and style is h1s:
        blocks.append(HRFlowable(width='100%', color=ACCENT, thickness=1.2,
                                 spaceBefore=0, spaceAfter=10))
    if level == 0:
        story.append(CondPageBreak(H1_THRESHOLD))
    story.extend(safe_keep_together(blocks))
    return p


def make_table(header, rows, ratios, style_extra=None, align_center_cols=()):
    data = [[Paragraph('<b>%s</b>' % c, cell_h) for c in header]]
    for r_i, row in enumerate(rows):
        line = []
        for c_i, c in enumerate(row):
            st = cell_c if c_i in align_center_cols else cell
            line.append(Paragraph(c, st))
        data.append(line)
    widths = [r * AVAIL_W for r in ratios]
    assert sum(widths) <= AVAIL_W + 0.5, 'table overflow: %.1f > %.1f' % (sum(widths), AVAIL_W)
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    ts = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        ts.append(('BACKGROUND', (0, i), (-1, i),
                   TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    if style_extra:
        ts.extend(style_extra)
    t.setStyle(TableStyle(ts))
    return t


def code_block(lines):
    paras = [Paragraph(html_mod.escape(l) if l else ' ', code_st) for l in lines]
    t = Table([[paras]], colWidths=[AVAIL_W * 0.96], hAlign='CENTER')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('LINEBEFORE', (0, 0), (0, -1), 2, ACCENT),
        ('LEFTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
    ]))
    return t


def callout_row(stats):
    """stats: list of (big, label) tuples -> one row of stat boxes."""
    n = len(stats)
    gap = 10
    box_w = (AVAIL_W - gap * (n - 1)) / n
    cells = []
    for big, lab in stats:
        inner = Table([[Paragraph('<b>%s</b>' % big, stat_big)],
                       [Paragraph(lab, stat_lbl)]], colWidths=[box_w])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9),
            ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
            ('TOPPADDING', (0, 1), (-1, 1), 2),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        cells.append(inner)
    row = []
    for i, c in enumerate(cells):
        row.append(c)
        if i < n - 1:
            row.append(Spacer(gap, 1))
    wrap = Table([row], colWidths=[w for i, w in enumerate(
        [box_w if i % 2 == 0 else gap for i in range(2 * n - 1)])], hAlign='CENTER')
    wrap.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
    ]))
    return wrap


